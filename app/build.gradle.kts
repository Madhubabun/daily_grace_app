// Release signing comes from keystore.properties (local builds) or DG_* environment
// variables (GitHub Actions). Without either, the release APK falls back to the debug key
// so it still installs, but updates must always be signed with the same key.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(prop: String, env: String): String? =
    keystoreProps.getProperty(prop) ?: System.getenv(env)?.takeIf { it.isNotBlank() }

val releaseStoreFile = signingValue("storeFile", "DG_KEYSTORE_FILE")
val hasReleaseKey = releaseStoreFile != null && rootProject.file(releaseStoreFile).exists()

